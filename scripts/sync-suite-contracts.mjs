// Suite schemas are authoritative JSON. Generate data, complete-document DTOs,
// and native include tables; semantic validation stays in the native libraries.
const pascal = name => name.split(/[^a-zA-Z0-9]+/).filter(Boolean).map(s => s[0].toUpperCase() + s.slice(1)).join('');
const snake = name => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replaceAll('-', '_').toLowerCase();
const banner = '// Generated by scripts/sync-contracts.mjs from contracts/. Do not edit.\n';
const assertions = new Set(['$schema','description','type','properties','required','additionalProperties','const','enum','oneOf','anyOf','not','items','minLength','maxLength','pattern','minimum','maximum','minItems','maxItems','uniqueItems','contains']);

function check(node) {
  for (const key of Object.keys(node)) if (!assertions.has(key) && !key.startsWith('x-')) throw Error(`Unsupported Suite schema keyword: ${key}`);
  if (node.type && !['object','array','string','integer','number','boolean'].includes(node.type)) throw Error(`Unsupported Suite type: ${node.type}`);
  if (node.additionalProperties !== undefined && typeof node.additionalProperties !== 'boolean') throw Error('Unsupported Suite additionalProperties');
  for (const child of Object.values(node.properties ?? {})) check(child);
  if (node.items) check(node.items);
  for (const group of ['oneOf','anyOf']) for (const child of node[group] ?? []) check(child);
  for (const key of ['not','contains']) if (node[key]) check(node[key]);
}
function ts(node) {
  if (Object.hasOwn(node,'const')) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(v=>JSON.stringify(v)).join(' | ');
  if (node.type === 'array') return `Array<${ts(node.items)}>`;
  if (node.type === 'object') {
    const fields=Object.entries(node.properties??{}).map(([key,value])=>`${JSON.stringify(key)}${(node.required??[]).includes(key)?'':'?'}: ${ts(value)}`);
    if (node.additionalProperties !== false) fields.push('[key: string]: unknown');
    let result=`{ ${fields.join('; ')} }`;
    if(node.oneOf)result+=` & (${node.oneOf.map(ts).join(' | ')})`;
    return result;
  }
  return ({string:'string',integer:'number',number:'number',boolean:'boolean'})[node.type]??'unknown';
}
const shape = node => JSON.stringify(node, (key,value)=>key==='$schema'||key==='description'?undefined:value);

export function suiteContractOutputs(all, defaults, corpus) {
  const schemas=Object.fromEntries(Object.entries(all).filter(([name])=>name.startsWith('suite-')).map(([name,schema])=>[name.slice(6),schema]));
  for(const schema of Object.values(schemas))check(schema);
  const output=new Map();
  output.set('typescript/src/suite-contracts.generated.ts',banner+'export const suiteSchemas = '+JSON.stringify(schemas)+' as const;\nexport const suiteDefaults = '+JSON.stringify(defaults)+' as const;\n');
  output.set('typescript/src/suite-types.generated.ts',banner+Object.entries(schemas).map(([name,schema])=>`export type Suite${pascal(name)} = ${ts(schema)};`).join('\n')+'\nexport interface SuiteDocumentMap {\n'+Object.keys(schemas).map(name=>`  ${JSON.stringify(name)}: Suite${pascal(name)};`).join('\n')+'\n}\n');
  for(const target of ['go/contracts','rust/contracts']) {
    output.set(`${target}/suite-defaults.json`,JSON.stringify(defaults,null,2)+'\n');
    output.set(`${target}/suite-conformance.json`,JSON.stringify(corpus,null,2)+'\n');
  }

  // Reuse structurally identical object DTOs. Every open object preserves its
  // unknown JSON fields, including nested capabilities and event payloads.
  const names=new Map(Object.entries(schemas).map(([name,schema])=>[shape(schema),`Suite${pascal(name)}`]));
  const nodes=new Map();
  function objectName(node, hint) {
    const key=shape(node); let name=names.get(key);
    if(!name){name=hint;let suffix=2;while(nodes.has(name)&&shape(nodes.get(name))!==key)name=hint+suffix++;names.set(key,name);}
    if(!nodes.has(name)){nodes.set(name,node);for(const [field,child]of Object.entries(node.properties??{}))native(child,`${name}${pascal(field)}`);}
    return name;
  }
  function native(node,hint,language='go') {
    let type=node.type??(Object.hasOwn(node,'const')?typeof node.const:node.enum?typeof node.enum[0]:undefined);
    if(type==='object'&&Object.keys(node.properties??{}).length)return objectName(node,hint);
    if(type==='object')return language==='go'?'map[string]json.RawMessage':'serde_json::Map<String, serde_json::Value>';
    if(type==='array')return language==='go'?'[]'+native(node.items,hint+'Item'): 'Vec<'+native(node.items,hint+'Item','rust')+'>';
    return (language==='go'?{string:'string',integer:'uint64',number:'float64',boolean:'bool'}:{string:'String',integer:'u64',number:'f64',boolean:'bool'})[type]??(language==='go'?'json.RawMessage':'serde_json::Value');
  }
  for(const [name,schema]of Object.entries(schemas))objectName(schema,`Suite${pascal(name)}`);
  let go=banner+'package noxmcp\n\nimport "encoding/json"\n\n';
  let rust=banner+'use serde::{Deserialize, Serialize};\n\n';
  const rustKeywords=new Set(['type','match','ref','self','loop','move','mod','use','in','where','impl','trait','enum','struct','fn','async','await','pub','crate','super','const','let','return','for','while','if','else']);
  for(const [name,node]of nodes) {
    const fields=Object.entries(node.properties??{}), required=new Set(node.required??[]);
    const secret=fields.some(([key])=>['apiKey','accessToken','secret','serviceCredential'].includes(key));
    go+=`type ${name} struct {\n`;
    rust+=`#[derive(Clone, ${secret?'':'Debug, '}Serialize, Deserialize, PartialEq)]\npub struct ${name} {\n`;
    for(const [key,child]of fields){
      const optional=!required.has(key), goType=native(child,name+pascal(key)), rustType=native(child,name+pascal(key),'rust');
      go+=`\t${pascal(key).replace(/Id$/,'ID')} ${optional?'*':''}${goType} \x60json:"${key}${optional?',omitempty':''}"\x60\n`;
      let field=snake(key);if(rustKeywords.has(field))field+='_';
      rust+=`    #[serde(rename = ${JSON.stringify(key)}${optional?', default, skip_serializing_if = "Option::is_none"':''})]\n    pub ${field}: ${optional?'Option<'+rustType+'>':rustType},\n`;
    }
    go+='\tExtra map[string]json.RawMessage `json:"-"`\n}\n';
    go+=`func (v ${name}) MarshalJSON() ([]byte, error) { type plain ${name}; return marshalSuiteDTO(plain(v),v.Extra) }\n`;
    go+=`func (v *${name}) UnmarshalJSON(data []byte) error { type plain ${name}; var p plain; extra,err:=unmarshalSuiteDTO(data,&p,[]string{${fields.map(([key])=>JSON.stringify(key)).join(',')}}); if err!=nil{return err}; *v=${name}(p); v.Extra=extra; return nil }\n\n`;
    if(secret)go+=`func (v ${name}) String() string { return "${name}(secrets redacted)" }\nfunc (v ${name}) GoString() string { return v.String() }\n`;
    rust+='    #[serde(flatten)]\n    pub extra: serde_json::Map<String, serde_json::Value>,\n}\n\n';
    if(secret)rust+=`impl std::fmt::Debug for ${name} { fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result { f.write_str("${name}(secrets redacted)") } }\n`;
  }
  for(const [name]of Object.entries(schemas)){
    const type=`Suite${pascal(name)}`;
    go+=`func Load${type}(data []byte) (${type},error) { return loadSuiteTyped[${type}](${JSON.stringify(name)},data) }\n`;
    rust+=`pub fn load_suite_${snake(name)}(input: &str) -> SuiteResult<${type}> { load_suite_typed(${JSON.stringify(name)},input) }\n`;
  }
  go+='\nconst (\n';rust+='\n';
  for(const [key,value]of Object.entries(defaults)){
    go+=`\tSuite${pascal(key).replace(/Ms$/,'MS')} = ${JSON.stringify(value)}\n`;
    rust+=`pub const ${snake(key).toUpperCase()}: ${typeof value==='string'?'&str':'u64'} = ${JSON.stringify(value)};\n`;
  }
  go+=')\n';
  rust+='\npub const SUITE_SCHEMAS: &[(&str, &str)] = &[\n'+Object.keys(schemas).map(name=>`    (${JSON.stringify(name)}, include_str!(${JSON.stringify('../contracts/suite-'+name+'.schema.json')})),`).join('\n')+'\n];\n';
  output.set('go/suite_types.generated.go',go);
  output.set('rust/src/suite_types.generated.rs',rust);
  return output;
}
