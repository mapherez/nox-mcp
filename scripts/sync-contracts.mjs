import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const banner = '// Generated by scripts/sync-contracts.mjs from contracts/. Do not edit.\n';

// Deliberately small, build-time translation of the subset used by our contracts.
// Unsupported assertions fail generation instead of silently weakening validation.
function zod(schema) {
  const supported = new Set(['$schema', 'description', 'type', 'properties', 'required', 'additionalProperties', 'propertyNames', 'oneOf', 'const', 'enum', 'minLength', 'maxLength', 'pattern', 'format', 'default', 'items']);
  for (const key of Object.keys(schema)) if (!supported.has(key)) throw new Error(`Unsupported contract keyword: ${key}`);
  let expression;
  if (schema.oneOf) {
    const values = (s, key) => s.oneOf ? s.oneOf.flatMap(v => values(v, key)) : Object.hasOwn(s.properties?.[key] ?? {}, 'const') ? [s.properties[key].const] : [];
    const discriminator = ['type', 'ok'].find(key => {
      const groups = schema.oneOf.map(s => [...new Set(values(s, key))]);
      return groups.every(g => g.length) && new Set(groups.flat()).size === groups.flat().length;
    });
    if (!discriminator) throw new Error('Contract oneOf requires disjoint literal discriminators.');
    expression = `z.discriminatedUnion(${JSON.stringify(discriminator)}, [${schema.oneOf.map(zod).join(', ')}])`;
  } else if (Object.hasOwn(schema, 'const')) expression = `z.literal(${JSON.stringify(schema.const)})`;
  // Existing protocol enum types were string (defaults came from JSON), not a literal union.
  else if (schema.enum) expression = `z.enum(${JSON.stringify(schema.enum)} as [string, ...string[]])`;
  else if (schema.type === 'object') {
    if (schema.propertyNames && JSON.stringify(schema.propertyNames) !== '{"type":"string"}') throw new Error('Unsupported propertyNames assertion.');
    if (!schema.properties) expression = `z.record(z.string(), ${zod(schema.additionalProperties ?? {})})`;
    else {
      const fields = Object.entries(schema.properties).map(([key, value]) => `${JSON.stringify(key)}: ${zod(value)}${(schema.required ?? []).includes(key) || Object.hasOwn(value, 'default') ? '' : '.optional()'}`);
      expression = `z.object({ ${fields.join(', ')} })`;
      if (schema.additionalProperties === false) expression += '.strict()';
      else if (schema.additionalProperties && Object.keys(schema.additionalProperties).length) expression += `.catchall(${zod(schema.additionalProperties)})`;
      else expression += '.passthrough()';
    }
  } else if (schema.type === 'array') expression = `z.array(${zod(schema.items)})`;
  else if (schema.type === 'string') {
    expression = schema.format === 'date-time' ? 'z.iso.datetime({ offset: true })' : 'z.string()';
    if (schema.minLength !== undefined) expression += `.min(${schema.minLength})`;
    if (schema.maxLength !== undefined) expression += `.max(${schema.maxLength})`;
    if (schema.format === 'uuid') expression += '.uuid()';
    else if (schema.format === 'date-time') { /* Keep the public ZodISODateTime type. */ }
    else if (schema.format) throw new Error(`Unsupported format: ${schema.format}`);
    if (schema.pattern) expression += `.regex(new RegExp(${JSON.stringify(schema.pattern)}))`;
  } else if (schema.type === 'boolean') expression = 'z.boolean()';
  else if (Object.keys(schema).every(key => key === 'description')) expression = 'z.unknown()';
  else throw new Error(`Unsupported contract schema: ${JSON.stringify(schema)}`);
  if (Object.hasOwn(schema, 'default')) expression += `.default(${JSON.stringify(schema.default)})`;
  return expression;
}

export async function syncContracts(directory = root, { check = false } = {}) {
  const source = resolve(directory, 'contracts');
  const names = (await readdir(source)).filter(name => name.endsWith('.schema.json')).sort();
  const schemas = Object.fromEntries(await Promise.all(names.map(async name => [name.replace('.schema.json', ''), JSON.parse(await readFile(resolve(source, name), 'utf8'))])));
  const variant = (schema, type) => {
    const found = schema.oneOf.find(s => s.properties?.type?.const === type);
    if (!found) throw new Error(`Missing contract variant: ${type}`);
    return found;
  };
  const equalDefinition = (official, embedded, name) => {
    const { $schema, ...definition } = official;
    if (!isDeepStrictEqual(definition, embedded)) throw new Error(`Inconsistent embedded contract: ${name}`);
  };
  equalDefinition(schemas.request, variant(schemas.server, 'request'), 'request');
  equalDefinition(schemas.response, schemas.desktop.oneOf.find(s => s.oneOf), 'response');
  equalDefinition(schemas.error, schemas.response.oneOf.find(s => s.properties?.ok?.const === false)?.properties.error, 'error');
  const defaults = JSON.parse(await readFile(resolve(source, 'defaults.json'), 'utf8'));
  const outputs = new Map();
  for (const target of ['go/contracts', 'rust/contracts']) for (const name of names) outputs.set(`${target}/${name}`, JSON.stringify(schemas[name.replace('.schema.json', '')], null, 2) + '\n');
  const corpus = JSON.parse(await readFile(resolve(source, 'conformance.json'), 'utf8'));
  for (const target of ['go/contracts', 'rust/contracts']) outputs.set(`${target}/conformance.json`, JSON.stringify(corpus, null, 2) + '\n');
  outputs.set('typescript/src/defaults.json', JSON.stringify(defaults, null, 2) + '\n');
  outputs.set('go/defaults.go', `${banner}package noxmcp\n\nconst BridgeProtocolVersion = ${JSON.stringify(defaults.bridgeProtocolVersion)}\nconst DefaultTimeoutMS = ${defaults.requestTimeoutMs}\nconst MaxPayloadBytes = ${defaults.maxPayloadBytes}\nconst MaxInFlightRequests = ${defaults.maxInFlightRequests}\n`);
  outputs.set('rust/src/defaults.rs', `${banner}pub const BRIDGE_PROTOCOL_VERSION: &str = ${JSON.stringify(defaults.bridgeProtocolVersion)};\npub const DEFAULT_TIMEOUT_MS: u64 = ${defaults.requestTimeoutMs};\npub const MAX_PAYLOAD_BYTES: usize = ${defaults.maxPayloadBytes};\npub const MAX_IN_FLIGHT_REQUESTS: usize = ${defaults.maxInFlightRequests};\n`);
  const definitions = {
    bridgeErrorSchema: schemas.error,
    bridgeAuthenticateSchema: variant(schemas.desktop, 'authenticate'),
    bridgeReadySchema: variant(schemas.desktop, 'ready'),
    bridgeRequestSchema: schemas.request,
    bridgeCancelSchema: variant(schemas.server, 'cancel'),
    bridgeResponseSchema: schemas.response,
    serverBridgeMessageSchema: schemas.server,
    desktopBridgeMessageSchema: schemas.desktop,
    toolManifestSchema: schemas.manifest,
  };
  outputs.set('typescript/src/contracts.generated.ts', banner + "import { z } from 'zod';\n\n" + Object.entries(definitions).map(([name, schema]) => `export const ${name} = ${zod(schema)};\n`).join('') + '\nexport const bridgeTicketSchema = bridgeAuthenticateSchema.shape.ticket;\n');
  const stale = [];
  for (const [path, content] of outputs) {
    const file = resolve(directory, path);
    const existing = await readFile(file, 'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; });
    if (existing?.replaceAll('\r\n', '\n') === content) continue;
    stale.push(path);
    if (!check) { await mkdir(dirname(file), { recursive: true }); await writeFile(file, content); }
  }
  // Removed schemas must not remain silently embedded in a language package.
  for (const target of ['go/contracts', 'rust/contracts']) {
    const files = await readdir(resolve(directory, target)).catch(error => { if (error.code !== 'ENOENT') throw error; return []; });
    for (const name of files.filter(name => name.endsWith('.schema.json') && !names.includes(name))) {
      stale.push(`${target}/${name}`);
      if (!check) await unlink(resolve(directory, target, name));
    }
  }
  if (check && stale.length) throw new Error(`Generated contracts are stale: ${stale.join(', ')}. Run npm run contracts:sync.`);
  return stale;
}

if (typeof process !== 'undefined' && process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/sync-contracts.mjs [--check]');
  await syncContracts(root, { check: process.argv.includes('--check') });
}
